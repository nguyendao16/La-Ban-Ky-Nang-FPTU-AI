"""Catalog -> CLO set -> JD comparison -> Chat with mocked inference only."""
from __future__ import annotations
import argparse
import json
from types import SimpleNamespace
from unittest.mock import Mock
from app.services import AdvisorService, CourseService, CLOSetService
from app.llm import LLMSettings


def mock_client(payload):
    client = Mock()
    client.responses.input_tokens.count.return_value = SimpleNamespace(input_tokens=100)
    client.responses.parse.return_value = SimpleNamespace(status="completed", output=[], output_parsed=payload)
    return client


def mock_payloads(clo_set):
    course = clo_set["courses"][0]
    evidence = [{"course_code": course["course_code"], "clo": course["clos"][0]["clo"]}]
    return ({"radar": mock_jd_radar(evidence), "comparison_type": "clo_jd_comparison", "overview": "MOCK: đối chiếu CLO enriched với JD.",
        "requirement_reviews": [{"jd_requirement": "SQL", "coverage": "related", "comment": "MOCK: kiểm thử điều phối, không đánh giá chất lượng LLM.", "evidence": evidence}],
        "conclusion": "MOCK: kết luận chỉ dựa trên nội dung CLO và JD."},
        {"reply": "MOCK: giải thích mối liên hệ CLO–JD của phiên.", "evidence": evidence})


def run_demo(*, curriculum_code, curriculum_source_id):
    catalog = CourseService(curriculum_mapping={curriculum_code: curriculum_source_id}, default_curriculum_code=curriculum_code)
    source = CLOSetService(catalog).build_clo_set(["ADY201m"])
    comparison, reply = mock_payloads(source)
    clients = [mock_client(comparison), mock_client(reply)]
    with AdvisorService(review_settings=LLMSettings(api_key="offline", stage="review"), chat_settings=LLMSettings(api_key="offline", stage="chat"), review_client=clients[0], chat_client=clients[1]) as advisor:
        snapshot = advisor.create_snapshot(source, "Python và SQL")
        snapshot, _ = advisor.review_snapshot(snapshot)
        snapshot, _ = advisor.chat_snapshot(snapshot, "CLO nào liên quan tới JD?")
    return {"courses": catalog.list_courses(), "clo_set": source,
        "session": {"session_id": snapshot["session_id"], "status": "ready"}, "history": snapshot["messages"],
        "mock_calls": {stage: {"preflight": client.responses.input_tokens.count.call_count, "generation": client.responses.parse.call_count} for stage, client in zip(["review", "chat"], clients)}}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--curriculum-code", required=True)
    parser.add_argument("--curriculum-source-id", required=True)
    args = parser.parse_args(argv)
    print(json.dumps(run_demo(curriculum_code=args.curriculum_code, curriculum_source_id=args.curriculum_source_id), ensure_ascii=False, indent=2))
    return 0


def mock_jd_radar(evidence):
    """Fixed demo values only; real JD axes and scores are generated by the LLM."""
    names = ['Lập trình', 'Xử lý dữ liệu', 'Phân tích', 'Triển khai', 'Truyền đạt kết quả']
    return {'overall_score': 2.3 if evidence else 0,
        'overall_comment': 'DEMO OFFLINE: điểm minh họa đối chiếu nội dung với JD, không đo năng lực cá nhân.',
        'axes': [{'name': name, 'description': f'DEMO: phạm vi minh họa cho {name}.',
            'score': 2.5 if evidence else 0, 'comment': 'DEMO OFFLINE: phân tích và điểm số được giả lập.',
            'evidence': evidence} for name in names]}


def mock_career_radar(profile, evidence):
    """Offline scores; new target definitions come from the pinned catalog."""
    if profile.get('target'):
        return {'overall_score': 2.3 if evidence else 0,
            'overall_comment': 'DEMO OFFLINE: điểm minh họa trong phạm vi năm trục, không đo năng lực cá nhân.',
            'axes': [{**axis, 'score': 2.5 if evidence else 0,
                'comment': 'DEMO OFFLINE: liên hệ nội dung được giả lập.', 'evidence': evidence}
                for axis in profile['target']['axes']]}
    tasks = [line[2:].strip() for line in profile['content'].splitlines() if line.startswith('- ')][:5]
    assert len(tasks) == 5
    return {'overall_score': 2.3 if evidence else 0, 'overall_comment': 'DEMO OFFLINE: điểm minh họa do mock cung cấp, không đo năng lực cá nhân.',
        'axes': [{'name': f"{i + 1}. {' '.join(task.split()[:5])}"[:60], 'description': task,
                  'score': 2.5 if evidence else 0, 'comment': 'DEMO OFFLINE: liên hệ nội dung được giả lập.',
                  'evidence': evidence} for i, task in enumerate(tasks)]}


